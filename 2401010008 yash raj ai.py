"""## Step 3: Privacy Masking and Rule-Based Threat Detection

### Aim
Mask sensitive identifiers and use a rule-based detector to identify possible phishing, malware, and ransomware indicators in sample messages.

### Procedure
1. Create a function to mask email addresses, IP addresses, and account IDs.
2. Define keywords associated with phishing, malware, and ransomware.
3. Check each message for matching keywords.
4. Display the masked message, detected category, matched keywords, and rule score.

The rule-based detector uses predefined keywords. Its results are indicators for review, not proof that a message is malicious.
"""

import re
import pandas as pd

# Mask sensitive identifiers
def mask_text(text):
    text = str(text)

    # Mask email addresses
    text = re.sub(
        r'\b[\w.-]+@[\w.-]+\.\w+\b',
        '[EMAIL]',
        text
    )

    # Mask IPv4 addresses
    text = re.sub(
        r'\b(?:\d{1,3}\.){3}\d{1,3}\b',
        '[IP]',
        text
    )

    # Mask account IDs such as account_id: 12345
    text = re.sub(
        r'(?i)(account_id\s*[:=]\s*)\w+',
        r'\1[ACCOUNT_ID]',
        text
    )

    return text


# Define threat keywords
threat_keywords = {
    "Phishing": [
        "verify your account",
        "password",
        "blocked",
        "urgent"
    ],
    "Malware": [
        "malware",
        "unknown file",
        "attachment",
        "download"
    ],
    "Ransomware": [
        "encrypted",
        "ransom",
        "restore access"
    ]
}


# Detect threats using keyword rules
def rule_detector(message):
    message = message.lower()

    matched = []
    categories = []

    for category, keywords in threat_keywords.items():
        for keyword in keywords:
            if keyword in message:
                matched.append(keyword)

                if category not in categories:
                    categories.append(category)

    if not matched:
        category = "Safe"
    else:
        category = ", ".join(categories)

    keyword_score = len(matched)

    return category, matched, keyword_score


# Analyze the sample messages
messages["masked_message"] = messages["message"].apply(mask_text)

results = messages["masked_message"].apply(rule_detector)

messages["threat_category"] = results.apply(lambda x: x[0])
messages["matched_keywords"] = results.apply(lambda x: x[1])
messages["keyword_score"] = results.apply(lambda x: x[2])

display(
    messages[
        [
            "masked_message",
            "threat_category",
            "matched_keywords",
            "keyword_score"
        ]
    ]
)

